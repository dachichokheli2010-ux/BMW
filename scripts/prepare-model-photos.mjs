import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import sharp from 'sharp';
import {allModels} from '../public/catalog.js';

// Resize only approved existing photographs. No synthesis, crop, recolouring or
// replacement of originals. Credit/license records remain attached to the source.
const root=fileURLToPath(new URL('../',import.meta.url));
const publicRoot=path.join(root,'public');
const directory=path.join(publicRoot,'images','responsive');
await fs.mkdir(directory,{recursive:true});
const photos=[...new Map(allModels.flatMap(model=>[...model.approvedPhotos.car,...model.approvedPhotos.engine]).map(photo=>[photo.src,photo])).values()].sort((a,b)=>a.src.localeCompare(b.src));
const prepared={};
async function prepare(photo){
  const input=path.resolve(publicRoot,photo.src);
  if(path.relative(publicRoot,input).startsWith('..'))throw Error('Photo must stay inside public.');
  const bytes=await fs.readFile(input),metadata=await sharp(bytes).metadata();
  const hash=createHash('sha256').update(bytes).digest('hex').slice(0,16);
  const variants=[];
  for(const width of [360,720,1200].filter(width=>width<metadata.width)){
    const src=`images/responsive/${hash}-${width}.webp`,destination=path.join(publicRoot,src);
    let info;
    try{await fs.access(destination);info=await sharp(destination).metadata();}
    catch{info=await sharp(bytes).resize({width,withoutEnlargement:true}).webp({quality:82}).toFile(destination);}
    variants.push({src,width:info.width,height:info.height});
  }
  variants.push({src:photo.src,width:metadata.width,height:metadata.height});
  const tiny=await sharp(bytes).resize({width:20,withoutEnlargement:true}).blur(1).webp({quality:35}).toBuffer();
  prepared[photo.src]={width:metadata.width,height:metadata.height,variants,placeholder:`data:image/webp;base64,${tiny.toString('base64')}`};
}
for(let index=0;index<photos.length;index+=4)await Promise.all(photos.slice(index,index+4).map(prepare));
const entries=Object.fromEntries(Object.entries(prepared).sort(([a],[b])=>a.localeCompare(b)));
await fs.writeFile(path.join(publicRoot,'responsive-photo-data.js'),'// Generated by npm run photos:prepare from approved originals. Do not edit.\nexport const responsivePhotoData='+JSON.stringify(entries,null,2)+';\n');
console.log(`Prepared responsive WebP sizes and blur previews for ${photos.length} approved photographs.`);
