// Exercise the actual overlay controllers. Layout and browser-native modality
// still require visual QA; these checks protect selection, focus and dismissal.
const {window,document}=parseHTML('<html><body><button id="trigger" data-global-search>Search</button><dialog id="dialog"><button id="close" aria-label="Close dialog">Close</button><div id="dialogbody"></div></dialog></body></html>');
let active=document.body;
const storage=new Map();
Object.assign(globalThis,{window,document,location:new URL('https://apex.example/models'),localStorage:{getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value)},matchMedia:()=>({matches:true})});
Object.defineProperty(document,'activeElement',{get:()=>active});
window.HTMLElement.prototype.focus=function(){active=this;};
window.HTMLElement.prototype.getClientRects=function(){return [{}];};
window.HTMLElement.prototype.getBoundingClientRect=function(){return {left:100,right:900,top:100,bottom:800,width:800,height:700};};
window.HTMLElement.prototype.scrollIntoView=function(options){this.lastReveal=options;};
window.HTMLElement.prototype.scrollTo=function(options){this.scrollTop=options.top;};
window.HTMLElement.prototype.showModal=function(){this.open=true;this.setAttribute('open','');};
window.HTMLElement.prototype.close=function(){this.open=false;this.removeAttribute('open');this.dispatchEvent(new window.Event('close'));};
const key=(target,value,extra={})=>{const event=new window.Event('keydown',{bubbles:true,cancelable:true});Object.assign(event,{key:value,...extra});target.dispatchEvent(event);return event;};
const input=(target,value)=>{target.value=value;target.dispatchEvent(new window.Event('input',{bubbles:true}));};
const click=(target,extra={})=>{assert.ok(target,'Expected the control to exist');const event=new window.Event('click',{bubbles:true,cancelable:true});Object.assign(event,extra);target.dispatchEvent(event);return event;};
const cancel=modal=>{const event=new window.Event('cancel',{cancelable:true});modal.dispatchEvent(event);if(!event.defaultPrevented)modal.close();return event;};

const activated=[];
const search=mountSmartSearch({catalog:allModels,onModel:id=>activated.push(['model',id]),onTopic:id=>activated.push(['topic',id]),onCompare:ids=>activated.push(['compare',ids])});
const trigger=document.querySelector('#trigger');trigger.focus();click(trigger);
const searchDialog=document.querySelector('.global-search'),query=searchDialog.querySelector('input');
assert.equal(searchDialog.open,true);
assert.equal(document.documentElement.classList.contains('apex-search-open'),true,'Search locks background scrolling');
assert.equal(active,query,'Opening search focuses the query without relying on dialog browser defaults');
assert.ok(searchDialog.querySelector('[data-gs-close] svg path'),'Close uses an accessible vector icon');
assert.equal(searchDialog.querySelector('[data-gs-close]').getAttribute('aria-label'),'Close search');
assert.equal(searchDialog.querySelector('[data-gs-close]').textContent.trim(),'','Escape hint must be separate from the close icon');
input(query,'F10 M5');
assert.ok(searchDialog.querySelector('[data-gs-result]'));
key(query,'ArrowDown');assert.ok(query.getAttribute('aria-activedescendant'));
const activeOption=searchDialog.querySelector('#'+query.getAttribute('aria-activedescendant'));
assert.equal(activeOption.getAttribute('aria-selected'),'true');
assert.deepEqual(activeOption.lastReveal,{block:'nearest'},'Keyboard selection reveals the result inside the results scroller');
key(query,'Enter');assert.deepEqual(activated.at(-1),['model','f10-m5']);
assert.equal(searchDialog.open,false);assert.equal(active,trigger,'Closing restores the original control');
assert.equal(document.documentElement.classList.contains('apex-search-open'),false);
assert.equal(query.getAttribute('aria-expanded'),'false');

search.open();
assert.ok(searchDialog.querySelector('.gs-recents [data-gs-recent]'),'Selected searches are available as recent searches');
click(searchDialog.querySelector('[data-gs-category="Community"]'));
assert.equal(searchDialog.querySelectorAll('[role=option]').length,3,'Community filter only exposes the three public community routes');
assert.equal(searchDialog.querySelector('[data-gs-category="Community"]').getAttribute('aria-pressed'),'true');
input(query,'friends');key(query,'Enter');assert.deepEqual(activated.at(-1),['topic','community-friends']);
search.open('M3 vs M4');
assert.ok(searchDialog.querySelector('.gs-compare'));
key(query,'Enter');assert.equal(activated.at(-1)[0],'compare');assert.equal(activated.at(-1)[1].length,2);
search.open('intercooler');
assert.equal(cancel(searchDialog).defaultPrevented,true,'Escape clears a query before dismissing the dialog');
assert.equal(query.value,'');assert.equal(searchDialog.open,true);
cancel(searchDialog);assert.equal(searchDialog.open,false);
search.open();
click(searchDialog,{clientX:150,clientY:150});assert.equal(searchDialog.open,true,'Clicking interior sheet whitespace is not a backdrop click');
click(searchDialog,{clientX:0,clientY:0});assert.equal(searchDialog.open,false,'Backdrop click dismisses the sheet');
search.open('M5');
key(query,'ArrowDown',{isComposing:true});assert.equal(query.getAttribute('aria-activedescendant'),null,'IME composing does not move result selection');
const clearEvent=key(query,'Escape');assert.equal(clearEvent.defaultPrevented,true);assert.equal(query.value,'');
click(searchDialog.querySelector('[data-gs-close]'));assert.equal(searchDialog.open,false);
// Native dialogs queue their close event. Destruction must unlock immediately,
// even when its abort signal removes listeners before that event is delivered.
search.open();
searchDialog.close=function(){this.open=false;this.removeAttribute('open');queueMicrotask(()=>this.dispatchEvent(new window.Event('close')));};
search.destroy();assert.equal(document.querySelector('.global-search'),null);
assert.equal(document.documentElement.classList.contains('apex-search-open'),false,'Destroy unlocks scrolling before a queued native close event');
await Promise.resolve();

const modal=document.querySelector('#dialog'),body=document.querySelector('#dialogbody');
let selected=[];
const comparison=createComparisonController({catalog:allModels,getSelected:()=>selected,onSelectionChange:ids=>{selected=ids;},dialog:html=>{modal.classList.remove('comparison-dialog');body.innerHTML=html;modal.showModal();}});
comparison.open();assert.equal(modal.classList.contains('comparison-dialog'),true);assert.equal(body.querySelectorAll('.cmp-slot-empty').length,3);
click(body.querySelector('[data-cmp-pick="0"]'));assert.ok(body.querySelector('.cmp-picker'));
assert.equal(active,body.querySelector('[data-cmp-search]'));
input(body.querySelector('[data-cmp-search]'),'F10 M5');
click(body.querySelector('[data-cmp-choose="f10-m5"]'));assert.deepEqual(selected,['f10-m5']);assert.equal(body.querySelector('.cmp-picker'),null);
click(body.querySelector('[data-cmp-pick="1"]'));input(body.querySelector('[data-cmp-search]'),'G80');
click(body.querySelector('[data-cmp-choose="g80"]'));assert.deepEqual(selected,['f10-m5','g80']);
const table=body.querySelector('.cmp-scroll');table.scrollLeft=120;table.scrollTop=180;body.scrollTop=200;
click(body.querySelector('[data-cmp-units="imperial"]'));
assert.equal(body.querySelector('[data-cmp-units="imperial"]').getAttribute('aria-pressed'),'true');
assert.equal(body.querySelector('.cmp-scroll').scrollLeft,120);assert.equal(body.querySelector('.cmp-scroll').scrollTop,180);assert.equal(body.scrollTop,200,'Unit changes preserve both scroll containers');
click(body.querySelector('[data-cmp-pick="0"]'));
assert.equal(body.querySelector('[data-cmp-choose="f10-m5"]').disabled,true,'An already selected car cannot be chosen twice');
const escapePicker=key(body.querySelector('[data-cmp-search]'),'Escape');assert.equal(escapePicker.defaultPrevented,true);assert.equal(body.querySelector('.cmp-picker'),null);assert.equal(modal.open,true,'Escape closes the picker before the comparison');
click(body.querySelector('[data-cmp-remove="g80"]'));assert.deepEqual(selected,['f10-m5']);
click(body.querySelector('[data-cmp-pick="1"]'));input(body.querySelector('[data-cmp-search]'),'nonsense-no-car');assert.ok(body.querySelector('.cmp-no-results'));
modal.close();assert.equal(modal.classList.contains('comparison-dialog'),false,'The shared dialog does not retain comparison styling after close');
body.scrollTop=700;comparison.open();assert.equal(body.scrollTop,0);assert.equal(body.querySelector('.cmp-picker'),null,'Reopening clears stale picker state');
assert.deepEqual(selected,['f10-m5'],'Reopening retains the selected cars');
click(body.querySelector('[data-cmp-clear]'));assert.deepEqual(selected,[]);
click(body.querySelector('[data-cmp-preset="g80,g82-m4"]'));assert.deepEqual(selected,['g80','g82-m4']);
comparison.dispose();modal.close();

